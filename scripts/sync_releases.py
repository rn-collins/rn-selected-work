#!/usr/bin/env python3
"""Write data/releases.json, the one release record the site reads.

One entry per piece. The id is the piece's sources page address without /sources/:
  <account>/<slug>  for the fifteen accounts (ddw26/s12, htw/c14-02, ioo/c01-p01)
  aan/<slug>        for Ask a Neuroscientist (its page is /sources/<slug>)
  tfh/<slug>        for Tech From Here: NL (its page is /sources/tfh/<slug>)
The essay for a piece (/essays/<account>/<slug>, and the older copy under /writing/dutch-design-week)
carries the same id and is released with it.

releasedAt is the posting date in the piece's sources data (data/sources-*.json, data/aan-sources.json),
read as a Hawaii date. An undated piece gets releasedAt "" and hold true, and stays hidden.
hold, postUrls and galleryUrl are kept from the existing file, so they can be set by hand.
longFormUrl and sourcePageUrl are worked out here.

  python3 scripts/sync_releases.py          rewrite data/releases.json
  python3 scripts/sync_releases.py --check  exit 1 if data/releases.json is out of date
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = DATA / "releases.json"
BASE = "https://rn-selected-work.vercel.app"
SUBSCRIBE = "https://polymath-rn-collins.beehiiv.com/subscribe"

ACCOUNTS = {
    "ddw26": ["ddw26"], "venues": ["venues"], "makers": ["makers"], "editions": ["editions"],
    "ddw27": ["ddw27"], "dda": ["dda"], "htw": ["htw"], "ioo": ["ioo", "ioo-site"],
    "polymath": ["polymath", "polymath-rnc"], "fatnugs": ["fatnugs"], "clr": ["clr"],
    "museum": ["museum"], "film": ["film"], "kbyg": ["kbyg"], "jbd": ["jbd"],
    "aan-f": ["aan-f"],
}
ESSAY_ACCOUNTS = ["ddw26", "venues", "makers", "editions", "dda", "ddw27", "kbyg"]


def posts(name):
    return json.loads((DATA / name).read_text())["posts"]


def long_form(origin, essay_url):
    # The specific long-form piece: the on-site essay first, then an outside article. Never a home,
    # listing or subscribe page.
    if essay_url:
        return essay_url
    if origin and origin.get("kind") == "article" and origin.get("url") and origin["url"] != SUBSCRIBE:
        return origin["url"]
    return ""


def build(existing):
    essays = {
        f"{acct}/{e['id']}": f"{BASE}/essays/{acct}/{e['id']}"
        for acct in ESSAY_ACCOUNTS
        for e in posts(f"essays-{acct}.json")
    }
    rows = []

    def add(pid, date, origin, page):
        old = existing.get(pid, {})
        rows.append({
            "id": pid,
            "releasedAt": date or "",
            "hold": True if not date else bool(old.get("hold", False)),
            "postUrls": old.get("postUrls", {}),
            "longFormUrl": long_form(origin, essays.get(pid)),
            "sourcePageUrl": f"{BASE}{page}",
            "galleryUrl": old.get("galleryUrl", ""),
        })

    for p in posts("aan-sources.json"):
        add(f"aan/{p['slug']}", p["date"], p.get("origin"), f"/sources/{p['slug']}")
    for acct, files in ACCOUNTS.items():
        for f in files:
            for p in posts(f"sources-{f}.json"):
                add(f"{acct}/{p['slug']}", p["date"], p.get("origin"), f"/sources/{acct}/{p['slug']}")
    for p in posts("sources-tfh.json"):
        add(f"tfh/{p['slug']}", p["date"], p.get("origin"), f"/sources/tfh/{p['slug']}")

    ids = [r["id"] for r in rows]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        sys.exit(f"duplicate piece ids: {dupes}")
    orphans = sorted(set(essays) - set(ids))
    if orphans:
        sys.exit(f"essays with no sources page (no release date to follow): {orphans}")
    rows.sort(key=lambda r: r["id"])
    return {
        "note": "Generated by scripts/sync_releases.py from the sources data. A piece is public only when releasedAt "
                "(a Pacific/Honolulu date) is today or earlier and hold is false. hold, postUrls and galleryUrl may be "
                "edited by hand; rerun the script after any sources data change.",
        "timeZone": "Pacific/Honolulu",
        "pieces": rows,
    }


def main():
    existing = {}
    if OUT.exists():
        existing = {r["id"]: r for r in json.loads(OUT.read_text())["pieces"]}
    text = json.dumps(build(existing), indent=1, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("data/releases.json is out of date: run python3 scripts/sync_releases.py")
        print("data/releases.json is up to date")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
