// Long-form essays behind RN Collins' posts, one page per essay at /essays/<account>/<id>. The id is the same id
// as the matching sources page (/sources/<account>/<id>). The data files are generated by scripts/export_essays.py
// (data/essays-<account>.json); do not edit them by hand. An account with no essays yet is left out of every page.
export type Run = ["t", string] | ["b", string] | ["c", string[]];
export type Block =
  | { t: "h2" | "h3"; x: string }
  | { t: "p"; r: Run[] }
  | { t: "ul" | "ol"; items: Run[][] }
  | { t: "table"; head: Run[][]; rows: Run[][][] };
export type EssaySource = { id: string; label: string; url: string | null };
export type Essay = {
  id: string; registryId: string; title: string; subtitle: string; seoTitle: string; description: string;
  byline: string; date: string | null; words: number; blocks: Block[]; sources: EssaySource[];
};
export type EssayAccount = { key: string; name: string; blurb: string; essays: Essay[] };

const all = (d: { posts: unknown[] }) => d.posts as Essay[];

const definitions: Omit<EssayAccount, "essays">[] = [
  { key: "ddw26", name: "Dutch Design Week 2026",
    blurb: "Essays on items in the Dutch Design Week 2026 programme: what the listing says, what the research says, and what the record leaves open." },
  { key: "venues", name: "Dutch Design Week venues",
    blurb: "Essays on the Eindhoven places that host Dutch Design Week, traced through the archive." },
  { key: "makers", name: "Dutch Design Week makers",
    blurb: "Essays on makers and studios in the Dutch Design Week archive." },
  { key: "editions", name: "Dutch Design Week editions",
    blurb: "Essays on Dutch Design Week year by year, 2015 to 2025." },
  { key: "dda", name: "Dutch Design Awards",
    blurb: "Essays on the Dutch Design Awards year by year, from the official photo archive and the published record." },
  { key: "ddw27", name: "Dutch Design Week essays",
    blurb: "Essays on work in the Dutch Design Week 2026 programme." },
  { key: "kbyg", name: "Know Before You Grow",
    blurb: "Essays from RN Collins' Know Before You Grow series on Hawaiʻi cannabis rules, each traced to the laws and records it cites." },
];
const data: Record<string, Essay[]> = { ddw26: all(ddw26), venues: all(venues), makers: all(makers), editions: all(editions), dda: all(dda), ddw27: all(ddw27), kbyg: all(kbyg) };

export const essayAccounts: EssayAccount[] = definitions
  .map((d) => ({ ...d, essays: data[d.key] }))
  .filter((a) => a.essays.length > 0);

export function essayAccount(key: string) {
  return essayAccounts.find((a) => a.key === key);
}

export function essay(key: string, id: string) {
  return essayAccount(key)?.essays.find((e) => e.id === id);
}

// An essay is public with its piece: the same id as its sources page, released in data/releases.json
// (lib/releases.ts). Before that its address returns 404 and no index or sitemap lists it.
export function releasedEssays(key: string, now = new Date()) {
  const day = (id: string) => release(pieceId(key, id))?.releasedAt ?? "";
  return (essayAccount(key)?.essays ?? [])
    .filter((e) => isReleased(pieceId(key, e.id), now))
    .sort((a, b) => day(a.id).localeCompare(day(b.id)));
}

export function releasedEssay(key: string, id: string, now = new Date()) {
  const e = essay(key, id);
  return e && isReleased(pieceId(key, id), now) ? e : undefined;
}

export const essayCount = (now = new Date()) => essayAccounts.reduce((n, a) => n + releasedEssays(a.key, now).length, 0);
export const essayPath = (account: string, id: string) => `/essays/${account}/${id}`;
export const sourcesPath = (account: string, id: string) => `/sources/${account}/${id}`;
export const POLYMATH_SUBSCRIBE = "https://polymath-rn-collins.beehiiv.com/subscribe";

export function longDate(date: string) {
  return new Date(`${date}T12:00:00Z`).toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric", timeZone: "UTC" });
}

export function readingMinutes(e: Essay) {
  return Math.max(1, Math.round(e.words / 230));
}

export function host(url: string) {
  try { return new URL(url).hostname.replace(/^www\./, ""); } catch { return ""; }
}

// One switch for every essay page and index (lib/essays-config.ts).
export function essayRobots() {
  return ESSAYS_INDEXABLE ? { index: true, follow: true } : { index: false, follow: true };
}

// Open Graph and Twitter cards for the essay pages. The image is the site-wide card (app/opengraph-image.tsx).
const shareImage = { url: "/opengraph-image", width: 1200, height: 630, alt: "RN Selected Work by Rayven-Nikkita Collins" };
export function essayShare(title: string, description: string, path: string, type: "article" | "website", extra: { authors?: string[]; publishedTime?: string } = {}) {
  return {
    openGraph: { title, description, type, url: path, siteName: "RN Selected Work", images: [shareImage], ...extra },
    twitter: { card: "summary_large_image" as const, title, description, images: [shareImage.url] },
  };
}
