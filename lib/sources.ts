export function account(key: string) {
  return accounts.find((a) => a.key === key);
}

export function sourcePost(key: string, slug: string) {
  return account(key)?.posts.find((p) => p.slug === slug);
}

// A page is listed on its account index (and in the sitemap) from its posting day on, in the account's own
// time zone. The page itself exists ahead of time, so the printed address works on posting day.
// SOURCES_LIST_ALL=1 lists every page, for local previews only.
export function listed(a: Account, now = new Date()) {
  if (process.env.SOURCES_LIST_ALL === "1") return a.posts;
  const today = new Intl.DateTimeFormat("en-CA", { timeZone: a.timeZone }).format(now);
  // An undated post (date "") has a page but is not listed until it gets a posting date.
  return a.posts.filter((p) => p.date !== "" && p.date <= today);
}

export function longDate(date: string) {
  return new Date(`${date}T12:00:00Z`).toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric", timeZone: "UTC" });
}

export function host(url: string) {
  try { return new URL(url).hostname.replace(/^www\./, ""); } catch { return ""; }
}

export function entryCount(p: SourcePost) {
  return p.research.length + p.other.length + p.images.length;
}
