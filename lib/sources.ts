export function account(key: string) {
  return accounts.find((a) => a.key === key);
}

export function sourcePost(key: string, slug: string) {
  return account(key)?.posts.find((p) => p.slug === slug);
}

// A page exists, and is listed on its account index and in the sitemap, only once the piece is released in
// data/releases.json (lib/releases.ts): its posting date, a Hawaii date, has arrived and it is not on hold.
// Before that the address returns 404. SOURCES_LIST_ALL=1 lists every page, for local previews only
// (`next dev`); it has no effect in a production build.
export function listed(a: Account, now = new Date()) {
  if (process.env.SOURCES_LIST_ALL === "1" && process.env.NODE_ENV !== "production") return a.posts;
  return a.posts.filter((p) => isReleased(pieceId(a.key, p.slug), now));
}

export function releasedPost(key: string, slug: string, now = new Date()) {
  const p = sourcePost(key, slug);
  return p && isReleased(pieceId(key, slug), now) ? p : undefined;
}

export function longDate(date: string) {
  return new Date(`${date}T12:00:00Z`).toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric", timeZone: "UTC" });
}

export function host(url: string) {
  try { return new URL(url).hostname.replace(/^www\./, ""); } catch { return ""; }
}

export function entryCount(p: SourcePost) {
  return p.research.length + p.other.length + p.images.length;
}
