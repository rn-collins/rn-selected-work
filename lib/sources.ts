// Sources pages for RN Collins' own packages, one account per package family (fifteen accounts).
// Page address: /sources/<account>/<slug>. The data files are generated by
// render-kit/sources_export_ours.py (data/sources-<account>.json); do not edit them by hand.
// Ask a Neuroscientist keeps its own data (lib/aan-sources.ts) and its /sources/<mon-dd> addresses.
// The takeover packages (Polymath PM-RNC, museum, film) come from scripts/export_takeover_sources.py instead:
// data/sources-polymath-rnc.json (joins the polymath account), data/sources-museum.json, data/sources-film.json.
// A takeover reference may have no url (a source with no public copy, such as a recorded conversation); it is
// then listed without a link. `note` is the partnership line the package itself carries.
export type SourceLink = { label: string; url: string };
export type ImageCredit = { where: string; what: string; credit: string; url: string; card: boolean };
export type Origin = { kind: "article" | "listing" | "main"; label: string; url: string } | null;
export type SourcePost = {
  slug: string; date: string; id: string; title: string; series: string; origin: Origin;
  research: SourceLink[]; other: SourceLink[]; images: ImageCredit[]; note?: string;
};
export type Account = {
  key: string; name: string; blurb: string; timeZone: string; posts: SourcePost[]; intro?: string;
};

